  function translatedDate(text) {
    return text.replace(/\b(January|February|March|April|May|June|July|August|September|October|November|December|Jan|Feb|Mar|Apr|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\.?\s+(\d{1,2})(?=\b)/gi,
      (_match, month, day) => `${months[month[0].toUpperCase() + month.slice(1).toLowerCase()]} 月 ${Number(day)} 日`)
      .replace(/(\d{1,2}) 月 (\d{1,2}) 日\s*[–-]\s*(\d{1,2}) 月 (\d{1,2}) 日,?\s*(20\d{2})/g, '$5 年 $1 月 $2 日至 $3 月 $4 日')
      .replace(/(\d{1,2}) 月 (\d{1,2}) 日\s*[–-]\s*(\d{1,2}),?\s*(20\d{2})/g, '$4 年 $1 月 $2–$3 日')
      .replace(/(\d{1,2}) 月 (\d{1,2}) 日,?\s*(20\d{2})/g, '$3 年 $1 月 $2 日')
      .replace(/(\d{1,2}) 月 (\d{1,2}) 日\s*[–-]\s*(\d{1,2}) 月 (\d{1,2}) 日/g, '$1 月 $2 日至 $3 月 $4 日')
      .replace(/(\d{1,2}) 月 (\d{1,2}) 日\s*[–-]\s*(\d{1,2})/g, '$1 月 $2–$3 日');
  }

  function translateLine(source) {
    const bullet = /^\s*([•·▪‣–—-])\s*/.exec(source);
    const original = String(source || '').replace(/^\s*[•·▪‣–—-]\s*/, '').trim();
    if (!original) return source;
    const mapped = exact[original] || exact[original.replace(/[.]$/, '')];
    if (mapped) return (bullet ? `${bullet[1]} ` : '') + mapped;
    const ageRange = original.match(/^Ages? (\d+)[–-](\d+) by (.+)$/i);
    if (ageRange) return (bullet ? `${bullet[1]} ` : '') + `${translatedDate(ageRange[3])}前年龄须为 ${ageRange[1]}–${ageRange[2]} 岁`;
    const ageMinimum = original.match(/^At least (\d+) by (.+)$/i);
    if (ageMinimum) return (bullet ? `${bullet[1]} ` : '') + `${translatedDate(ageMinimum[2])}前须年满 ${ageMinimum[1]} 岁`;
    let value = translatedDate(original);
    value = value.replace(/\b(\d{4})\s+(?:summer|academic year)\b/gi, '$1 年暑期');
    value = value.replace(/\bSummer\s+(\d{4})\b/gi, '$1 年暑期');
    value = value.replace(/\b(\d{4})\s+total program cost\b/gi, '$1 年项目总费用');
    value = value.replace(/\b(\d{4})\s+reference\b/gi, '$1 年参考信息');
    value = value.replace(/\b(\d{4})\s+cycle\b/gi, '$1 年申请周期');
    value = value.replace(/\b(\d{4})\s+dates\b/gi, '$1 年日期');
    value = value.replace(/\b(\d{4})\s+(?:tuition|fees|costs)\b/gi, '$1 年费用');
    value = value.replace(/\b(\d+)(?:st|nd|rd|th)[- ]grade\b/gi, '$1 年级');
    value = value.replace(/\bgrades?\s+(\d+)\s*[-–]\s*(\d+)\b/gi, '$1–$2 年级');
    value = value.replace(/\b(?:age|ages)\s+(\d+)\s*[-–]\s*(\d+)\b/gi, '$1–$2 岁');
    value = value.replace(/\b(?:age|ages)\s+(\d+)\+\b/gi, '$1 岁及以上');
    value = value.replace(/\b(\d+)\s*[-–]\s*(\d+)\s*(weeks?|days?)\b/gi, '$1–$2 $3');
    value = value.replace(/\b(\d+)\s*-\s*week\b/gi, '$1 周');
    value = value.replace(/\b(\d+)\s*-\s*credit\b/gi, '$1 学分');
    value = value.replace(/\b(\d+)\s+or\s+(\d+)\s+(weeks?|days?)\b/gi, '$1 或 $2 $3');
    value = value.replace(/\bor\b/gi, '或').replace(/\band\b/gi, '及');
    for (const [english, chinese] of phrases) {
      const escaped = english.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      value = value.replace(new RegExp(`\\b${escaped}\\b`, 'gi'), chinese);
    }
    value = value.replace(/\b(\d+)\s*周\b/g, '$1 周');
    value = value.replace(/\b(\d+)\s*天\b/g, '$1 天');
    value = value.replace(/\b(\d+)\s*学分\b/g, '$1 学分');
    value = value.replace(/\s+([，。；：])/g, '$1');
    return (bullet ? `${bullet[1]} ` : '') + value;
  }

  function translate(value) {
    if (value == null) return value;
    if (Array.isArray(value)) return value.map(translate);
    return String(value).split(/(\r?\n)/).map(part => /\r?\n/.test(part) ? part : translateLine(part)).join('');
  }

