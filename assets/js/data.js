if (Array.isArray(window.SS_PROGRAM_CATALOG_TOP100)) {
  const existingPrograms = PROGRAMS.concat(window.SS_PROGRAM_CATALOG_EXPANSION || []);
  const normalizeCatalogName = value => String(value || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
  const replacementPrograms = window.SS_PROGRAM_CATALOG_TOP100.map(program => {
    const host = normalizeCatalogName(program.host && program.host.en);
    const name = normalizeCatalogName(program.name && program.name.en);
    const existing = existingPrograms.find(candidate => {
      const candidateHost = normalizeCatalogName(candidate.host && candidate.host.en);
      const candidateName = normalizeCatalogName(candidate.name && candidate.name.en);
      const hostMatch = candidateHost === host || candidateHost.includes(host) || host.includes(candidateHost);
      return hostMatch && (candidateName === name || candidateName.includes(name) || name.includes(candidateName));
    });
    const sameInstitution = existingPrograms.find(candidate => {
      const candidateHost = normalizeCatalogName(candidate.host && candidate.host.en);
      return candidateHost === host || candidateHost.includes(host) || host.includes(candidateHost);
    });
    const officialHost = (() => {
      try { return new URL(program.website || '').hostname.toLowerCase(); }
      catch { return ''; }
    })();
    const websiteDomain = officialHost.split('.').slice(-2).join('.');
    const institutionalLogoDomain = host.includes('johns hopkins') ? 'jhu.edu' : websiteDomain;
    return Object.assign({}, existing || {}, program, {
      name: program.name,
      host: program.host,
      discovery: program.discovery || (window.SS_PROGRAM_DISCOVERY && window.SS_PROGRAM_DISCOVERY.programs[program.id]) || null,
      location: existing && existing.location ? existing.location : program.location,
      logoDomain: program.logoDomain || institutionalLogoDomain || (existing && existing.logoDomain) || (sameInstitution && sameInstitution.logoDomain) || null,
      source: { officialUrl:program.officialInfo.programUrl, verified:true, checked:program.officialInfo.dataCycle, notes:'Official information and data cycle are listed in the source workbook.' },
      spreadsheetSource: { officialUrl:program.officialInfo.sourceUrl, verified:true, checked:program.officialInfo.dataCycle }
    });
  });
  PROGRAMS.splice(0, PROGRAMS.length, ...replacementPrograms);
} else if (Array.isArray(window.SS_PROGRAM_CATALOG_EXPANSION)) {
  const originalProgramsById = new Map(PROGRAMS.map(program => [program.id, program]));
  const knownProgramIds = new Set(PROGRAMS.map(program => program.id));
  window.SS_PROGRAM_CATALOG_EXPANSION.forEach(program => {
    const existing = program && program.existingId
      ? originalProgramsById.get(program.existingId)
      : null;
    if (existing) {
      existing.logoDomain = program.logoDomain || existing.logoDomain;
      existing.spreadsheetSource = program.source || null;
      if (program.source && program.source.verified) {
        existing.catalogStatus = 'official-source-listed';
        existing.source = program.source;
        existing.location = program.location || existing.location;
        existing.duration = program.duration || existing.duration;
        existing.tuition = program.tuition || existing.tuition;
        existing.website = program.website || existing.website;
      } else if (program.catalogStatus === 'spreadsheet-provisional') {
        existing.catalogStatus = 'spreadsheet-provisional';
      }
      if (program.catalogStatus === 'paused') {
        existing.catalogStatus = 'paused';
        existing.tagline = program.tagline || existing.tagline;
      }
      return;
    }
    if (program && program.id && !knownProgramIds.has(program.id)) {
      PROGRAMS.push(program);
      knownProgramIds.add(program.id);
    }
  });
}

