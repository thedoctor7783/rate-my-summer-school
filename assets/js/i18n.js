/* small helper */
function t(key, lang) { return (STRINGS[lang || currentLang()] || {})[key] || key; }
function currentLang() {
  try { return localStorage.getItem('ss.lang') || 'en'; } catch { return 'en'; }
}
function setLang(l) {
  try { localStorage.setItem('ss.lang', l); } catch {}
  document.documentElement.lang = (l === 'zh') ? 'zh' : 'en';
  if (typeof render === 'function') render();
}
window.SSI18N = { STRINGS, t, currentLang, setLang };
